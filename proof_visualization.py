# === Plot 2: Figure-8 Knot Topology (Information Flow Manifold) ===
ax2 = fig.add_subplot(122, projection='3d')
t = np.linspace(0, 2*np.pi, 500)
x, y, z = figure_eight_knot(t)

# Color map based on the parameter t to visualize the flow
colors = plt.cm.viridis(t / (2*np.pi))
for i in range(len(t)-1):
    ax2.plot(x[i:i+2], y[i:i+2], z[i:i+2], color=colors[i], linewidth=4)

ax2.set_title("Figure-8 Knot ($4_1$): Information Flow Manifold")
ax2.set_xlabel("X")
ax2.set_ylabel("Y")
ax2.set_zlabel("Z")
ax2.grid(False) # Remove gridlines for a cleaner look

# === Animation: Gradient Descent and Knot Rotation ===

# Initial state for gradient descent animation (starting at n=3.3)
n_start = 3.3
gd_point, = ax1.plot(n_start, InformationFunctional(n_start), 'go', markersize=10, label="System State")

def update(frame):
    # Update Gradient Descent
    total_frames = 150
    n_end = n_star
    
    if frame < total_frames:
        n_current = n_end + (n_start - n_end) * np.exp(-5 * frame/total_frames)
        gd_point.set_data(n_current, InformationFunctional(n_current))
    else:
        gd_point.set_data(n_star, InformationFunctional(n_star))

    # Update Knot Rotation
    ax2.view_init(elev=20., azim=frame * 0.5)
    return gd_point,

# Create the animation
print("\nGenerating Academic Visualization (Animation)...")
ani = animation.FuncAnimation(fig, update, frames=400, interval=30, blit=False, repeat=True)

