import numpy as np
import matplotlib.pyplot as plt
from mpl_toolkits.mplot3d import Axes3D
from scipy.special import lambertw
import matplotlib.animation as animation

# Configuration for academic style visualization
plt.rcParams.update({
    "font.family": "serif",
    "font.size": 12,
    "axes.labelsize": 14,
    "axes.titlesize": 16
})

# 1. Calculate n* (as done in the main proof code)
arg = -1/(2*np.e)
W_val = lambertw(arg, k=-1)
n_star = -W_val.real
D = 3

# 2. Define the Information Functional (Potential Energy Landscape)
def InformationFunctional(n):
    # Calculate the functional value
    F_n = n*np.log(2*n) - 0.5*n**2
    # Shift the functional so the minimum (at n*) is at 0 for visualization
    F_min = n_star*np.log(2*n_star) - 0.5*n_star**2
    return F_n - F_min

# 3. Define the Figure-8 Knot Parametrization
def figure_eight_knot(t):
    # Standard parametrization for 4_1 knot
    x = (2 + np.cos(2*t)) * np.cos(3*t)
    y = (2 + np.cos(2*t)) * np.sin(3*t)
    z = np.sin(4*t)
    return x, y, z

# 4. Setup the Visualization Figure
fig = plt.figure(figsize=(15, 7))
plt.suptitle("Axiomatic Framework Visualization: Gradient Descent and Topology", fontsize=18)

# === Plot 1: Information Functional and Gradient Descent ===
ax1 = fig.add_subplot(121)
n_values = np.linspace(2.0, 3.5, 500)
F_values = InformationFunctional(n_values)

ax1.plot(n_values, F_values, 'k-', linewidth=2, label='Information Functional $\mathcal{F}(n)$')
ax1.axvline(n_star, color='r', linestyle='--', label=f'$n^*$ ≈ {n_star:.4f} (Minimum)')
ax1.axvline(D, color='b', linestyle=':', label='$D=3$ (Topological Requirement)')

